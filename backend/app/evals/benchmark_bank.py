def list_benchmark_cases(
    limit: int | None = None,
    document_type: str | None = None,
    difficulty: str | None = None,
) -> list[BenchmarkCase]:
    cases = list(BENCHMARK_CASES)
    if document_type:
        cases = [case for case in cases if case.expected_document_type == document_type]
    if difficulty:
        cases = [case for case in cases if case.difficulty == difficulty]
    return cases[:limit] if limit else cases


def benchmark_summary() -> dict[str, object]:
    distribution: dict[str, int] = {}
    difficulty_distribution: dict[str, int] = {}
    answerable = 0
    for case in BENCHMARK_CASES:
        distribution[case.expected_document_type] = (
            distribution.get(case.expected_document_type, 0) + 1
        )
        difficulty_distribution[case.difficulty] = (
            difficulty_distribution.get(case.difficulty, 0) + 1
        )
        if case.should_answer:
            answerable += 1
    return {
        "total_cases": len(BENCHMARK_CASES),
        "answerable_cases": answerable,
        "unsupported_cases": len(BENCHMARK_CASES) - answerable,
        "document_type_distribution": distribution,
        "difficulty_distribution": difficulty_distribution,
    }

